"""Stretch goal: factory vs human baseline.

Scores a hand-written agent definition and a factory-produced one against the
*same* generated eval set, and writes a comparison showing where each wins.

    python scripts/baseline_compare.py --run runs/<run> \
        --baseline demos/hr_policy/handwritten_agent.json \
        --docs demos/hr_policy/docs

The comparison is only meaningful because the eval set was generated before
either definition was scored against it, and neither definition was tuned on
it by hand.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from forgeai.agent_runtime import RunnableAgent
from forgeai.config import FactoryConfig
from forgeai.docs import chunk_documents, load_documents
from forgeai.llm import Ledger, LLMClient
from forgeai.schemas import AgentDefinition, EvalSet
from forgeai.stages.judge import run_evaluation


def evaluate(definition: AgentDefinition, docs_dir: Path, eval_set: EvalSet, client, seed: int):
    docs, _ = load_documents(docs_dir)
    chunks = chunk_documents(
        docs, definition.retrieval.chunk_size, definition.retrieval.chunk_overlap
    )
    agent = RunnableAgent(definition, chunks, client, corpus_dir=docs_dir)
    return run_evaluation(agent, eval_set, client, iteration=0, seed=seed)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True, help="a completed factory run directory")
    ap.add_argument("--baseline", required=True, help="the hand-written agent.json")
    ap.add_argument("--docs", required=True)
    ap.add_argument("--out")
    args = ap.parse_args()

    run_dir = Path(args.run)
    cfg = FactoryConfig()
    client = LLMClient(cfg.model, Ledger(cfg.budget))

    eval_set = EvalSet.load(run_dir / "evalset.json")
    factory_def = AgentDefinition.load(run_dir / "agent.json")
    human_def = AgentDefinition.load(args.baseline)

    print(f"Scoring both agents on the same {len(eval_set.cases)} generated cases\n")
    print("factory agent...")
    f_card, f_results = evaluate(factory_def, Path(args.docs), eval_set, client, cfg.seed)
    print("hand-written agent...")
    h_card, h_results = evaluate(human_def, Path(args.docs), eval_set, client, cfg.seed)

    f_by_id = {r.case_id: r for r in f_results}
    h_by_id = {r.case_id: r for r in h_results}
    factory_wins = [
        cid for cid in f_by_id
        if f_by_id[cid].passed and not h_by_id[cid].passed
    ]
    human_wins = [
        cid for cid in f_by_id
        if h_by_id[cid].passed and not f_by_id[cid].passed
    ]

    lines = [
        "# Factory vs hand-written baseline",
        "",
        f"Both agents were scored on the same {len(eval_set.cases)} cases from "
        f"`{run_dir.name}/evalset.json`, generated from the documents before either "
        "was evaluated.",
        "",
        "| | Factory | Hand-written |",
        "|---|---|---|",
        f"| Score | **{f_card.score:.3f}** | **{h_card.score:.3f}** |",
        f"| Passed | {f_card.passed}/{f_card.total} | {h_card.passed}/{h_card.total} |",
        f"| Tools attached | {factory_def.tools or 'none'} | {human_def.tools or 'none'} |",
        f"| top_k | {factory_def.retrieval.top_k} | {human_def.retrieval.top_k} |",
        "",
    ]
    for kind in sorted(set(f_card.by_kind) | set(h_card.by_kind)):
        f_b = f_card.by_kind.get(kind, {})
        h_b = h_card.by_kind.get(kind, {})
        lines.append(
            f"- **{kind}**: factory {f_b.get('passed', 0)}/{f_b.get('total', 0)}, "
            f"hand-written {h_b.get('passed', 0)}/{h_b.get('total', 0)}"
        )
    lines.append("")

    lines += [f"## Where the factory wins ({len(factory_wins)})", ""]
    for cid in factory_wins:
        r = h_by_id[cid]
        lines += [
            f"- **{cid}**: {r.question}",
            f"  - hand-written failed as `{r.failure_category}`: "
            f"{(r.answer or '(empty)')[:160]}",
        ]
    if not factory_wins:
        lines.append("_None._")
    lines.append("")

    lines += [f"## Where the human wins ({len(human_wins)})", ""]
    for cid in human_wins:
        r = f_by_id[cid]
        lines += [
            f"- **{cid}**: {r.question}",
            f"  - factory failed as `{r.failure_category}`: "
            f"{(r.answer or '(empty)')[:160]}",
        ]
    if not human_wins:
        lines.append("_None._")
    lines += [
        "",
        "## Caveat",
        "",
        "The eval set was generated by the factory, so it tests what the factory",
        "thought was worth testing. That is a real advantage to the factory and the",
        "comparison should be read with it in mind: a hand-written agent optimised",
        "for questions the generator never thought to ask would not get credit here.",
        "",
    ]

    out = Path(args.out) if args.out else run_dir / "BASELINE_COMPARISON.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nfactory {f_card.score:.3f} vs hand-written {h_card.score:.3f}")
    print(f"Written: {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
